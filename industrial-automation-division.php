    jQuery(document).ready(function ($) {

        function animateOnScroll() {

            $('.animate-on-scroll, .product-head, .product-text').each(function () {

                var elementTop = $(this).offset().top;
                var windowBottom = $(window).scrollTop() + $(window).height();

                if (windowBottom > elementTop + 100) {
                    $(this).addClass('show');
                }

            });

        }

        animateOnScroll();

        $(window).on('scroll', function () {
            animateOnScroll();
        });

        function scrollToProductCategories() {
            var target = document.getElementById('product-categories');
            if (!target) {
                return;
            }

            // Pin section to viewport top so the full cover is visible (header overlays dark bg)
            var top = target.getBoundingClientRect().top + window.pageYOffset;
            window.scrollTo({ top: Math.max(Math.round(top), 0), behavior: 'smooth' });
        }

        $('a[href="#product-categories"]').on('click', function (e) {
            e.preventDefault();
            history.pushState(null, '', '#product-categories');
            scrollToProductCategories();
        });

        if (window.location.hash === '#product-categories') {
            if ('scrollRestoration' in history) {
                history.scrollRestoration = 'manual';
            }
            setTimeout(scrollToProductCategories, 50);
        }

    });
</script>

